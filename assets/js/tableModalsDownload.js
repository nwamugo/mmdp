function toggleCSS() {
  $('.modal-body-potential-partnerships')[0].classList.toggle(
    'org-potential-partnership:nth-child(8n+8)'
  );
}

function downloadTableModal(
  modalNode,
  canvasHeight,
  orientation,
  pdfText,
  pdfTextLeftMargin,
  pdfTextTopMargin,
  pdfImageXPosition,
  pdfImageYPosition,
  fileName,
  type
) {
  toggleCSS();
  html2canvas(modalNode, {
    height: canvasHeight,
    onrendered: function(canvas) {
      try {
        toggleCSS();
        var pageData = canvas.toDataURL('image/png');
        var modalNodeOriginalHeight = '495px';
        if (type === 'pdf') {
          var pdf = new jsPDF(orientation, 'px', 'a4');

          //get a4 paper size in px
          var pdfInternalHeight = pdf.internal.pageSize.getHeight();
          var pdfInternalWidth = pdf.internal.pageSize.getWidth();

          //One page pdf shows the canvas height generated by html pages.
          var pdfPageHeight =
            (canvas.width / pdfInternalWidth) * pdfInternalHeight;

          //html page height without pdf generation
          var htlmPageHeight = canvas.height;

          pdf.setFontSize(18);
          pdf.text(pdfText, pdfTextLeftMargin, pdfTextTopMargin);

          pdf.internal.scaleFactor = 1.7;

          //When the content does not exceed the range of pdf page display, there is no need to paginate. If it does, paginate
          if (htlmPageHeight < pdfPageHeight) {
            pdf.addImage(pageData, 'PNG', pdfImageXPosition, pdfImageYPosition);
          } else {
            while (htlmPageHeight > 0) {
              pdf.addImage(
                pageData,
                'PNG',
                pdfImageXPosition,
                pdfImageYPosition
              );
              htlmPageHeight -= pdfPageHeight;
              pdfImageYPosition -= pdfInternalHeight;

              //Avoid adding blank pages
              if (htlmPageHeight > 0) {
                pdf.addPage(fileName);
              }
            }
          }
          pdf.save(fileName);
        } else if ((type = 'png')) {
          download(fileName, pageData);
        } else if ((type = 'jpg')) {
          pageData = canvas.toDataURL('image/jpeg');
          download(fileName, pageData);
        }
        modalNode.style.height = modalNodeOriginalHeight;
      } catch (error) {
        throw error;
      }
    }
  });
}

$('.modal-popup').click(function() {
  let modalPopup = document.getElementById('modal-hamburger-popup');
  modalPopup.classList.toggle('modal-show');
});

$('body').on('click', function(event) {
  if (event.target.className !== 'modal-hamburger modal-popup') {
    if (event.target.className !== 'modal-popup-upper') {
      $('.modal-popup-menu').removeClass('modal-show');
    }
  }
});

$(
  '#modal-save-as-png, #modal-save-as-jpg, #modal-save-as-pdf, #modal-save-svg'
).click(function() {
  var stateName = getTrimmedStateNameFromUrl('pdf');
  var element = document.getElementById('lgaName');
  var lgaName = element.textContent;
  var fileStateName = getTrimmedStateNameFromUrl('btn');
  var fileLgaName = lgaName.toLowerCase().replace(' ', '-');
  var modalNode = $('.modal-body-potential-partnerships')[0];
  modalNode.style.height = '100%';
  var canvasHeight = 20000;
  var pdfText = `Partnership and Collaboration Report - ${lgaName}, ${stateName} State`;
  var orientation = 'l';
  var pdfTextLeftMargin = 30;
  var pdfTextTopMargin = 20;
  var pdfImageXPosition = 30;
  var pdfImageYPosition = 30;

  switch (this.id) {
    case 'modal-save-as-png':
      downloadTableModal(
        modalNode,
        canvasHeight,
        orientation,
        pdfText,
        pdfTextLeftMargin,
        pdfTextTopMargin,
        pdfImageXPosition,
        pdfImageYPosition,
        `${fileLgaName}-${fileStateName}-potential-partnerships-report.png`,
        'png'
      );
      break;
    case 'modal-save-as-jpg':
      downloadTableModal(
        modalNode,
        canvasHeight,
        orientation,
        pdfText,
        pdfTextLeftMargin,
        pdfTextTopMargin,
        pdfImageXPosition,
        pdfImageYPosition,
        `${fileLgaName}-${fileStateName}-potential-partnerships-report.jpg`,
        'jpg'
      );
      break;
    case 'modal-save-as-pdf':
      downloadTableModal(
        modalNode,
        canvasHeight,
        orientation,
        pdfText,
        pdfTextLeftMargin,
        pdfTextTopMargin,
        pdfImageXPosition,
        pdfImageYPosition,
        `${fileLgaName}-${fileStateName}-potential-partnerships-report.pdf`,
        'pdf'
      );
      break;
    default:
      break;
  }
});
